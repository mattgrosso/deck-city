// THE PRICE LIST, written out: `yarn price` prices every card in budget
// (src/game/core/economy/priceList.js, by the tables in economy.js) and
// writes docs/ECONOMY.md. Run it after changing a card or a value.
import { writeFileSync } from 'node:fs'
import { priceList, offTheLine, valueOfStartingDeck } from '@/game/core/economy/priceList'
import { VALUE, HORIZON, SPEND, CYCLE, FAIR, BARGAINS, NEIGHBOURS, CLEARS_PER_TURN, STRIKE_EVERY } from '@/game/core/economy/economy'

const L = priceList()
const out = []
const p = (s = '') => out.push(s)
const n = (x) => (x === null || x === undefined ? '-' : (x === Infinity ? '∞' : String(x)))
const tag = (f) => ({ loss: '▼ loss', deal: '▲ deal', bargain: '★ bargain', off: '◆ off its tier', fair: '' }[f] ?? f)

p('# The economy: everything in budget')
p()
p('Generated by `yarn price` from `src/game/core/economy/economy.js` (the values) and `priceList.js` (the pricing). Do not edit by hand; change a value or a card and run it again. `economy.test.js` fails when anything lands off the line without a named bargain.')
p()
p(`**The unit is one budget**, one coin of this turn's treasury. A trade is FAIR between ${FAIR.low} and ${FAIR.high} (what you get over what you pay). Off that line is a mistake unless it is a named **bargain**.`)
p()
p('| one of | budget | why |')
p('|---|---|---|')
const WHY = {
  budget: 'the unit',
  revenue: `a point every turn for ${HORIZON} turns, at ${SPEND} spent (use-it-or-lose-it, five cards to spend it on)`,
  population: 'the win condition; anchored so a lone house lands fair',
  jobs: 'a job keeps one person out of the unemployment Crime; shared, so half',
  status: `a dead draw about every ${CYCLE} turns until cleared`,
  draw: 'one more choice this turn',
  discard: 'thinning a bad draw',
  buy: 'one more purchase at the city row this turn: a fair buy\'s surplus, a turn sooner',
  rollover: `about 2 kept a turn, for ${HORIZON} turns, at ${SPEND}`
}
Object.entries(VALUE).forEach(([k, v]) => p(`| ${k} | ${Math.round(v * 100) / 100} | ${WHY[k] ?? ''} |`))
p()
p(`Lasting effects count over **${HORIZON} turns**; the deck comes round every **${CYCLE}**. A "next door" bonus assumes ${NEIGHBOURS.good} good neighbour and ${NEIGHBOURS.bad} bad one (players chase the first and dodge the second). A facility clears ${CLEARS_PER_TURN} status cards a turn. Disasters strike every ${STRIKE_EVERY} turns.`)
p()
p(`The starting deck is worth **${valueOfStartingDeck()}** budget over its cost.`)
p()
const off = offTheLine(L)
p(`## Off the line (${off.length})`)
p()
if (!off.length) p('Nothing. Every card is fair or a named bargain.')
off.forEach(x => p(`- ${tag(x.flag)} **${x.name}** (\`${x.key}\`): cost ${n(x.cost)}, gain ${n(x.gain)}, ratio ${n(x.ratio)}`))
p()
p('## Bargains (cheap or dear on purpose)')
p()
Object.entries(BARGAINS).forEach(([k, why]) => p(`- \`${k}\`: ${why}`))
p()
const table = (title, rows, cols) => {
  p(`## ${title}`)
  p()
  p(`| ${cols.map(c => c[0]).join(' | ')} |`)
  p(`|${cols.map(() => '---').join('|')}|`)
  rows.forEach(r => p(`| ${cols.map(c => n(c[1](r))).join(' | ')} |`))
  p()
}
table('Playing a card (its cost against one build)', L.plays, [['card', r => r.name], ['cost', r => r.cost], ['gives', r => r.gain], ['ratio', r => r.ratio], ['', r => tag(r.flag)], ['made of', r => r.note]])
table('Buying from the city row (price + build cost against one build and a spare)', L.buys, [['card', r => r.name], ['price', r => r.cost], ['build', r => r.play], ['gives', r => r.gain], ['ratio', r => r.ratio], ['', r => tag(r.flag)]])
table('Goals (free; the reward now plus the Monument card over the horizon)', L.goals, [['goal', r => r.name], ['tier', r => r.tier], ['now', r => r.now], ['monument', r => r.monument], ['total', r => r.gain], ['tier average', r => r.tierMean], ['', r => tag(r.flag)]])
table('What the game does to you', L.threats, [['what', r => r.name], ['worth', r => r.value], ['', r => r.note]])

writeFileSync(new URL('../docs/ECONOMY.md', import.meta.url), `${out.join('\n')}\n`)
console.log(`docs/ECONOMY.md written: ${L.plays.length} plays, ${L.buys.length} buys, ${L.goals.length} goals, ${off.length} off the line`)
